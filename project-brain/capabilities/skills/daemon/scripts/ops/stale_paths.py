@dataclass(frozen=True)
class DriftRule:
    action: str
    category: str
    regexes: tuple[re.Pattern[str], ...]
    summary_label: str
    suggestion: str
    # Deterministic replacements: list of (pattern, replacement) pairs.
    # When non-empty, issues matching this rule are auto-fixable via sed.
    sed_replacements: tuple[tuple[re.Pattern[str], str], ...] = ()


