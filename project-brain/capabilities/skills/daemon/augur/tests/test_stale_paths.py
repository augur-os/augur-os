def test_scan_dry_run_d0_ignores_stale_cached_report_when_newer_hardening_omits_category(
    monkeypatch,
    tmp_path: Path,
):
    repo_root = tmp_path / "repo"
    state_root = tmp_path / "state"
    repo_root.mkdir()
    monkeypatch.setenv("AUGUR_STATE", str(state_root))

    report_dir = state_root / "reports"
    report_dir.mkdir(parents=True)
    stale_report = report_dir / "adr270-enforcement-latest.json"
    stale_report.write_text(
        json.dumps(
            {
                "summary": {
                    "issue_count": 2,
                    "documentation_issue_count": 5,
                },
                "issues": [],
                "documentation_issues": [],
            }
        ),
        encoding="utf-8",
    )

    adaptive_report_dir = state_root / "adaptive" / "reports"
    adaptive_report_dir.mkdir(parents=True)
    hardening_report = adaptive_report_dir / "hardening-latest.json"
    hardening_report.write_text(
        json.dumps(
            {
                "categories": [
                    {
                        "name": "auto-tab-registry",
                        "actionable_count": 0,
                        "outcome": "clean",
                    }
                ]
            }
        ),
        encoding="utf-8",
    )
    future = Path(__file__).resolve().stat().st_mtime + 1000
    os.utime(stale_report, (1, 1))
    os.utime(hardening_report, (future, future))

    result = stale_paths.scan(_ctx(repo_root, dry_run=True, difficulty=0))

    assert result.issues == []
    assert "[cached report]" not in result.summary
    assert result.health == "verified"


