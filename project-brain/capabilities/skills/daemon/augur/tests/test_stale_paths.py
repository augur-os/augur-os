def _load_module():
    module_file = Path(__file__).resolve().parents[2] / "scripts" / "ops" / "stale_paths.py"
    spec = importlib.util.spec_from_file_location("stale_paths", module_file)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules["stale_paths"] = mod
    spec.loader.exec_module(mod)
    return mod


stale_paths = _load_module()


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _ctx(project_root: Path, **kwargs) -> OpsContext:
    return OpsContext(project_root=project_root, **kwargs)


def test_scan_detects_adr270_drift_classes_and_skips_archival_docs(tmp_path: Path):
    repo_root = tmp_path / "repo"
    runtime_path = "runtime" + "/coverage/coverage-summary.json"
    data_path = "augur" + "/" + "data/actions/status.yaml"
    mcp_path = "augur" + "/" + "mcp/__init__.py"

    _write(
        repo_root / ".github" / "scripts" / "legacy_runtime.py",
        f'coverage_file = "{runtime_path}"\n',
    )
    _write(
        repo_root / "src" / "legacy_data.ts",
        f'const legacyPath = "{data_path}";\n',
    )
    _write(
        repo_root / "plugins" / "observability" / "skills" / "demo" / "scripts" / "legacy_mcp.py",
        f'legacy = "{mcp_path}"\n',
    )
    _write(
        repo_root / "plugins" / "observability" / "skills" / "demo" / "augur" / "README.md",
        "# demo\n\nGenerated by ADR-270 migration. Update from SKILL.md.\n",
    )
    _write(
        repo_root / "docs" / "decisions" / "ADR-test.md",
        "Historical note about runtime logs and augur data paths.\n",
    )

    result = stale_paths.scan(_ctx(repo_root))

    actions = {issue["action"] for issue in result.issues}
    files = {issue["file"] for issue in result.issues}

    assert actions == {
        "legacy-runtime-path",
        "legacy-augur-data-path",
        "legacy-augur-mcp-path",
    }
    assert "docs/decisions/ADR-test.md" not in files
    assert "documentation issue(s) tracked separately" in result.summary
    assert result.severity == "warning"
    assert result.health == "degraded"


