def _out(*args: object, **kwargs: object) -> None:
    sep = kwargs.get("sep", " ")
    end = kwargs.get("end", "\n")
    file = kwargs.get("file", sys.stdout)
    file.write(sep.join(str(arg) for arg in args) + str(end))


# ---------------------------------------------------------------------------
# ADR Assembly
# ---------------------------------------------------------------------------


def generate_adr(report: dict[str, Any], adr_number: int) -> str:
    """Assemble the full ADR markdown from all sections."""
    hub_title = report.get("audit", {}).get("hub_title", "Unknown")

    sections = [
        generate_metadata(adr_number, hub_title),
        generate_audit_summary(report),
        generate_wow_effect_section(report),
        generate_context(report),
        generate_decision(report),
    ]

    notes = get_user_choices(report).get("notes", "")
    if notes:
        sections.extend(
            [
                "## User Notes",
                "",
                notes,
                "",
            ]
        )

    audit = report.get("audit", {}) or {}
    report_id = str(audit.get("report_id", audit.get("hub_id", "unknown")) or "unknown")
    scope = str(audit.get("scope", "hub") or "hub")
    route_prefix = str(audit.get("route_prefix", "") or "")
    if scope == "extension":
        audit_ref = f"`{report_id}` extension audit ({route_prefix})"
    else:
        audit_ref = f"`{report_id}` hub audit"

    sections.extend(
        [
            generate_consequences(report),
            "## Alternatives Considered",
            "",
            "This ADR was auto-generated by the dashboard hardening audit engine (ADR-065).",
            "No manual alternatives were evaluated.",
            "",
            "## References",
            "",
            "- ADR-065: Dashboard hardening workflow automation (parent)",
            f"- Audit report: {audit_ref}",
            f"- Audit timestamp: {audit.get('timestamp', '')}",
            "",
            generate_implementation_prompt(report, adr_number),
        ]
    )

    return "\n".join(sections)


